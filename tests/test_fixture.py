def test_the_difficulty_weight_decides_who_gets_a_bonus(season):
    """At weight 0 the tool is a pure stars table; at 0.5 hard targets pay.

    This is the live-season evidence behind the shipped default. If a future
    change makes the weight inert, this test fails.
    """
    stars = build_ranking(score_season(season, PRESETS["stars"]), bonuses=7)
    balanced = build_ranking(score_season(season, PRESETS["balanced"]), bonuses=7)
    hard = build_ranking(score_season(season, PRESETS["hard-target"]), bonuses=7)

    assert set(stars.recipients) != set(balanced.recipients), (
        "the difficulty weight changed nobody's bonus, so it is decorative")
    assert set(hard.recipients) != set(stars.recipients)


def test_the_default_preset_is_balanced():
    assert Weights().difficulty == 0.5
    assert resolve_weights().difficulty == 0.5
    assert PRESETS["stars"].difficulty == 0.0
    assert PRESETS["hard-target"].difficulty == 1.0


def test_config_file_overrides_survive_resolution(tmp_path):
    config = tmp_path / "weights.json"
    config.write_text(json.dumps({"difficulty": 0.75, "missed_attack": -3.0}),
                      encoding="utf-8")
    weights = resolve_weights(preset="balanced", config_path=str(config),
                              overrides={"bonuses": 3})
    assert weights.difficulty == 0.75
    assert weights.missed_attack == -3.0
    assert weights.bonuses == 3


def test_defense_mode_is_usable_on_real_data(season):
    weights = Weights(use_defense=True, difficulty=0.3)
    result = score_season(season, weights)
    ranking = build_ranking(result, bonuses=7)
    assert len(ranking.ranked) == 16
    scored = [p for p in result.players if p.defense_per_star is not None]
    assert scored, "defense numbers should be produced"
    # The worst defender must be identifiable, which the old formula could not do.
    worst = min(scored, key=lambda p: p.defense_per_star)
    best = max(scored, key=lambda p: p.defense_per_star)
    assert best.defense_per_star > worst.defense_per_star
    assert worst.defense_per_star < 0.5
