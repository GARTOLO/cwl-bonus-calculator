"""Regression tests against a real 7-round CWL season (anonymised).

Generated by tools/make_fixture.py from an actual season: same town hall spread,
same mirror behaviour, the same rushed bases, a no-show and a late substitute.
Names are replaced, every number is real. These are the numbers that made the
scoring decisions in docs/SCORING.md.
"""
from __future__ import annotations

import json
import re
from pathlib import Path

import pytest

from cwlbonus.config import PRESETS, Weights, resolve_weights
from cwlbonus.model import Season
from cwlbonus.ranking import build_ranking
from cwlbonus.scoring import score_season

FIXTURE = Path(__file__).parent / "fixtures" / "season_sample.json"


@pytest.fixture(scope="module")
def season() -> Season:
    return Season.from_dict(json.loads(FIXTURE.read_text(encoding="utf-8")))


def test_fixture_is_fully_anonymised():
    """Guard rail: the fixture must never carry a real identity.

    Tag-agnostic on purpose - it asserts the placeholders are well formed rather
    than naming the real clan, which would itself be a leak.
    """
    data = json.loads(FIXTURE.read_text(encoding="utf-8"))
    assert data["clan_tag"] == "#TESTCLAN"
    assert data["clan_name"] == "Test Clan"
    for war in data["wars"]:
        assert war["mine"]["clan_name"] == "Test Clan"
        assert re.fullmatch(r"Opponent \d{2}", war["theirs"]["clan_name"])
        assert re.fullmatch(r"#OPP\d{2}", war["theirs"]["clan_tag"])
        for member in war["mine"]["members"]:
            assert re.fullmatch(r"Player \d{2}", member["name"]), member["name"]
            assert re.fullmatch(r"#P\d{3}", member["tag"]), member["tag"]
        for member in war["theirs"]["members"]:
            assert re.fullmatch(r"Enemy \d{2,3}", member["name"]), member["name"]
            assert re.fullmatch(r"#P\d{3}", member["tag"]), member["tag"]


def test_season_shape(season):
    result = score_season(season, PRESETS["balanced"])
    assert result.wars_processed == 7
    assert result.attacks_processed == 104
    assert len(result.players) == 16
    assert season.number_of_rounds == 7


def test_cwl_is_mirror_based_in_practice(season):
    """The assumption the whole attack formula rests on, measured not assumed."""
    deltas: list[int] = []
    for war in season.wars:
        mine, theirs = war.mine.lineup(), war.theirs.lineup()
        my_slot = {m.tag: i for i, m in enumerate(mine, 1)}
        their_slot = {m.tag: i for i, m in enumerate(theirs, 1)}
        for member in mine:
            for attack in member.attacks:
                if attack.defender_tag in their_slot:
                    deltas.append(their_slot[attack.defender_tag] - my_slot[member.tag])
    exact = deltas.count(0) / len(deltas)
    assert exact > 0.95, f"only {exact:.1%} exact mirrors"
    # Outliers are negligible: at most one attack in the season was more than
    # one slot away from its mirror.
    outliers = [d for d in deltas if abs(d) >= 2]
    assert len(outliers) <= 1, f"unexpected drift: {outliers}"


def test_every_player_used_at_most_one_attack_per_war(season):
    """The basis for attacks_missed = wars_played - attacks_used."""
    for war in season.wars:
        for member in war.mine.members:
            assert len(member.attacks) <= 1, member.name


def test_rusher_detector_fires_on_real_maps(season):
    result = score_season(season, PRESETS["balanced"])
    assert len(result.rusher_corrections) == 11
    # Every correction only ever removes levels.
    assert all(c.counted_as < c.town_hall for c in result.rusher_corrections)


def test_rusher_cap_changes_nothing_here(season):
    """The cap is insurance: on this season it costs nothing."""
    base = score_season(season, Weights(rusher_max_cut=2))
    wide = score_season(season, Weights(rusher_max_cut=99))
    assert len(base.rusher_corrections) == len(wide.rusher_corrections)


def test_participation_edge_cases_are_present(season):
    result = score_season(season, PRESETS["balanced"])
    missed = [p for p in result.players if p.attacks_missed]
    assert len(missed) == 1, "the fixture should contain exactly one no-show"
    assert missed[0].attacks_missed == 1
    assert missed[0].penalty_points == -2.0
    subs = [p for p in result.players if p.wars_played == 1]
    assert subs, "the fixture should contain a late substitute"


def test_late_substitute_cannot_win_by_default_but_can_be_excluded(season):
    result = score_season(season, PRESETS["balanced"])
    everyone = build_ranking(result, bonuses=7, min_wars=0)
    restricted = build_ranking(result, bonuses=7, min_wars=4)
    assert not everyone.ineligible
    assert len(restricted.ineligible) == 1


def test_two_players_share_a_rank_instead_of_being_ordered_arbitrarily(season):
    result = score_season(season, PRESETS["balanced"])
    ranking = build_ranking(result, bonuses=7)
    tied = [rp for rp in ranking.ranked if rp.tied]
    assert len(tied) == 2
    assert tied[0].rank == tied[1].rank
    assert tied[0].player.total == tied[1].player.total


def test_ranking_is_deterministic_under_input_permutation(season):
    result = score_season(season, PRESETS["balanced"])
    baseline = [rp.player.name for rp in build_ranking(result, 7).ranked]
    shuffled = Season.from_dict(season.to_dict())
    shuffled.wars = list(reversed(shuffled.wars))
    for war in shuffled.wars:
        war.mine.members = list(reversed(war.mine.members))
    other = score_season(shuffled, PRESETS["balanced"])
    assert [rp.player.name for rp in build_ranking(other, 7).ranked] == baseline


